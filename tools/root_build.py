#!/usr/bin/env python3
"""root_build: build the modules that OAI.lean imports and no Comparator configuration needed, in chunks, with the memory valve.

Purpose: `import OAI` needs an .olean for each of its 91,762 modules; 6,461 of them (the root module OAI itself excluded from this
tool) were never built because no configuration's closure reaches them. This lists them (tools/root_build_status.py logic), orders
them by import-closure size so dependencies come first, and builds them with `lake build` through the throttled toolchain
(ext/sysroot-throttled, LEAN_SLOTS compile slots, taskset), under tools/vmamon.py and tools/memvalve.py, in chunks. Steps:
  1. restore: Lake treats a module's .c and .c.hash as tracked outputs, and the pipeline archived them, so a build that imports an
     archived module would recompile it. Unpack only the .c and .c.hash members of every archive/*.tar.zst (the large .setup.json files
     are regenerated by Lake and are skipped). --no-restore skips this.
  2. pilot: build the first --pilot modules and compare the number of modules Lake reports as built with the number asked for; if it is
     far larger the restore did not work, and the tool stops before spending hours.
  3. chunks of --chunk modules: wait for memory and disk, build, record, then archive the .c, .c.hash and .setup.json files of the
     modules built in that chunk (tar | zstd, verified, then removed), which keeps the transient disk use to one chunk.
Stops after the current chunk if results/root-build/STOP exists. Resumable: the unbuilt list is recomputed on every start.
Records go to results/root-build/batches.jsonl and driver.log. Does not build the root module OAI (its compile is the import itself).
Usage: root_build.py [--chunk 1500] [--pilot 30] [--limit N] [--lean-slots 6] [--build-cpus 6-15] [--no-restore] [--dry-run]
"""
import os, sys, re, json, time, glob, shutil, argparse, datetime, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from memvalve import MemoryValve, mem_avail_gib
ap = argparse.ArgumentParser()
ap.add_argument('--chunk', type=int, default=1500); ap.add_argument('--pilot', type=int, default=30); ap.add_argument('--limit', type=int, default=0)
ap.add_argument('--lean-slots', type=int, default=6); ap.add_argument('--build-cpus', default='6-15')
ap.add_argument('--start-avail-gib', type=float, default=20); ap.add_argument('--min-free-gib', type=float, default=15)
ap.add_argument('--no-restore', action='store_true'); ap.add_argument('--dry-run', action='store_true'); a = ap.parse_args()
base = os.path.abspath(os.path.join(os.path.dirname(__file__), '..')); root = base + '/src/lean'; bld = root + '/.lake/build'; lib = bld + '/lib/lean'
R = base + '/results/root-build'; os.makedirs(R + '/logs', exist_ok=True)
free_gib = lambda: shutil.disk_usage('/home').free / 2**30


def log(m):
    line = f"{datetime.datetime.now().astimezone().isoformat(timespec='seconds')} root_build: {m}"
    open(R + '/driver.log', 'a').write(line + '\n'); print(line, flush=True)


def unbuilt():
    rows = [json.loads(l) for l in open(base + '/results/oai-closure-sizes.jsonl')]
    miss = [(r['in_repo_closure'], r['module']) for r in rows if r['module'] != 'OAI' and not os.path.exists(os.path.join(lib, *r['module'].split('.')) + '.olean')]
    return [m for _, m in sorted(miss)]


def restore():
    t0 = time.time(); arcs = sorted(glob.glob(base + '/archive/*.tar.zst'), key=os.path.getmtime)
    for i, arc in enumerate(arcs, 1):
        r = subprocess.run(['tar', '--zstd', '-xf', arc, '-C', bld, '--wildcards', '*.c', '*.c.hash'], capture_output=True, text=True)
        log(f"restore {i}/{len(arcs)} {os.path.basename(arc)}: {'ok' if r.returncode == 0 else 'tar exit %d: %s' % (r.returncode, r.stderr[:120])} ({time.time() - t0:.0f} s)")


def run_lake(tag, mods):
    """lake build MODS under vmamon and the memory valve. Returns (record, built module names)."""
    while mem_avail_gib() < a.start_avail_gib:
        log(f"waiting for memory: {mem_avail_gib():.1f} GiB available, need {a.start_avail_gib:.0f}"); time.sleep(30)
    need = a.min_free_gib + 0.007 * len(mods)
    while free_gib() < need:
        log(f"waiting for disk: {free_gib():.0f} GiB free, need {need:.0f}"); time.sleep(60)
    mon = f'{R}/logs/{tag}.mon'; t = time.time()
    proc = subprocess.Popen(['python3', '-I', base + '/tools/vmamon.py', '--out', mon, '--interval', '0.5', '--label', f'root-build-{tag}', '--',
                             'taskset', '-c', a.build_cpus, base + '/ext/sysroot-throttled/bin/lake', 'build'] + mods, cwd=root,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                            env=dict(os.environ, LEAN_SYSROOT=base + '/ext/sysroot-throttled', LEAN_SLOTS=str(a.lean_slots)))
    valve = MemoryValve(proc.pid, log=log)
    while proc.poll() is None:
        try: valve.step()
        except Exception as e: log(f'valve error: {type(e).__name__}: {e}')
        time.sleep(2)
    valve.release()
    rec = dict(tag=tag, asked=len(mods), wall_s=round(time.time() - t, 1), free_gib_after=round(free_gib(), 1))
    built = []
    try:
        s = json.load(open(mon + '/summary.json')); txt = open(mon + '/stdout.log', errors='replace').read()
        built = [m for m, _ in re.findall(r"Built (\S+) \(([\d.]+)s\)", txt)] + [m for m, _, _ in re.findall(r"Built (\S+) \((\d+)m ([\d.]+)s\)", txt)]
        rec.update(exit=s['exit_code'], built=len(built), peak_vmas=s['peak_per_process_vmas_sampled'], vmamon_class=s['classification'])
        if s['exit_code'] != 0: rec['log_tail'] = txt[-600:]
    except Exception as e: rec['monitor_error'] = str(e)[:100]
    open(R + '/batches.jsonl', 'a').write(json.dumps(rec) + '\n')
    return rec, built


def archive(name, built):
    files = []
    for m in built:
        st = 'ir/' + '/'.join(m.split('.'))
        files += [f for f in (st + '.c', st + '.c.hash', st + '.setup.json') if os.path.exists(f'{bld}/{f}')]
    if not files: return
    lst = f'{R}/archive.lst'; open(lst, 'w').write('\n'.join(files) + '\n'); out = f'{base}/archive/{name}.tar.zst'
    p = subprocess.run(f"nice -n 10 tar -C {bld} -cf - --files-from {lst} | zstd -T4 -3 -q -o {out}", shell=True)
    t = subprocess.run(['zstd', '-tq', out])
    if p.returncode == 0 and t.returncode == 0:
        for f in files: os.remove(f'{bld}/{f}')
        log(f"archived {name}: {len(files)} files, {os.path.getsize(out) / 2**20:.0f} MiB")
    else: log(f"ARCHIVE FAILED {name}; originals kept")


todo = unbuilt()
if a.limit: todo = todo[:a.limit]
log(f"{len(todo)} modules to build; free disk {free_gib():.0f} GiB; chunk {a.chunk}, pilot {a.pilot}, slots {a.lean_slots}, cpus {a.build_cpus}")
if a.dry_run: print('\n'.join(todo[:5]), '...', todo[-3:], sep='\n'); sys.exit(0)
if not a.no_restore: restore()
run = time.strftime('%m%d%H%M'); k = 0
if a.pilot and len(todo) > a.pilot:
    rec, built = run_lake(f'{run}-pilot', todo[:a.pilot])
    log(f"pilot: asked {rec['asked']}, built {rec.get('built')}, exit {rec.get('exit')}, {rec['wall_s']:.0f} s")
    if rec.get('exit') != 0 or rec.get('built', 10**9) > 2 * a.pilot + 200:
        log("pilot did not behave (failed, or Lake rebuilt far more than asked: the restore is probably incomplete); stopping"); archive(f'root-{run}-pilot', built); sys.exit(2)
    archive(f'root-{run}-pilot', built); todo = unbuilt()
    if a.limit: todo = todo[:a.limit]
while todo:
    if os.path.exists(R + '/STOP'): log('STOP file present; exiting after the current chunk boundary'); break
    chunk = todo[:a.chunk]; k += 1
    rec, built = run_lake(f'{run}-{k}', chunk)
    log(f"chunk {k}: asked {rec['asked']}, built {rec.get('built')}, exit {rec.get('exit')}, {rec['wall_s']:.0f} s, peak mappings {rec.get('peak_vmas')}, free {rec['free_gib_after']} GiB")
    archive(f'root-{run}-{k}', built)
    if rec.get('exit') != 0: log('build failed; see batches.jsonl log_tail; stopping'); sys.exit(1)
    todo = unbuilt()
    if a.limit: todo = todo[:a.limit]
log(f"done: {len(unbuilt())} modules still unbuilt")
